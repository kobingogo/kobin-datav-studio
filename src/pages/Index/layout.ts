/**
 * 落地页展台环的几何参数 —— 单一事实来源。
 *
 * 为什么要抽出来
 * ------------------------------------------------------------------
 * 这些数字原先散在 ring.tsx（RADIUS / SPREAD）与 panel.tsx（W / H / 亮度指数）里，
 * 且互相耦合：站位间距决定相邻展台是否相交，展台宽度决定正面站占屏多少，
 * 亮度衰减指数决定最外侧那几块还剩多少对比度。改任何一个都会牵动另外两个，
 * 而"看起来挤了 / 看不清"只能靠肉眼判断，改完再靠肉眼确认 —— 很容易来回试。
 *
 * 所以：
 *   · 参数集中在这里，panel.tsx / ring.tsx 只读不算
 *   · 改动前后用 `node tools/arc-fit.mjs` 过一遍透视投影，
 *     看"屏幕上的实际像素间距 / 投影宽度 / 剩余亮度"，而不是靠感觉
 *
 * ── 站位间距与"能同时看清几块"的关系 ─────────────────────────
 * 展台固定朝向圆心外的径向，所以一块站的正对程度 = cos(它与相机方向夹角)。
 * 超过 ±60° 之后 cos 开始塌陷，投影宽度被 cos 压掉，展台退化成竖条：
 *
 *   夹角   facing=cos^1.1   投影宽度(相对正面)   实测读图
 *    0°       1.00            100%               满亮、抬起
 *   ±30°      0.87             87%               清晰
 *   ±40°      0.75             76%               可读（现有 4 站就是这个）
 *   ±60°      0.47             50%               偏暗但完整
 *   ±80°      0.15             17%               几乎全黑
 *
 * 结论：任意时刻稳定可读的只有「正面 + 左右各一」= 3 块。
 * 站位数从 4 涨到 6 改变的是**轮播一圈的长度**，不是同屏可见数——
 * 底部进度条与左侧面板承担全部 6 条的元信息，逐站切换去看即可。
 * 若一定要同屏 6 块全可读，只能把弧压到 ±50° 内，展台随之缩到 ~1.4 宽、
 * 正面站只剩 400px（占屏 21%），且相邻块在屏幕上互相相交。
 */

export const RING = {
  /** 环半径（世界单位）。相机 z=9.6，正面站距相机约 5.2 */
  radius: 4.4,

  /**
   * 站位间距（度）。
   *
   * 40° 是读感与"相邻不相离"的折中：
   *   · 侧翼站仍有 76% 投影宽度，是完整矩形而不是竖条
   *   · 相邻站圆心弦长 2·R·sin(20°) = 3.01，略小于展台宽 3.2 —— 屏幕上
   *     实测重叠约 180px，形成"一整面屏墙"的密度；这是想要的效果，
   *     改成小于展台宽就会散成一排孤立的屏
   *
   * 注意 6×40° = 240° ≠ 360°，所以这是一段**开口弧**，环上有一处 120° 的缺口。
   * 由此带来两条约束，ring.tsx 里必须遵守：
   *   1. 「当前选中谁」会改变可见集合（靠后那几块落在缺口里），
   *      所以不能用"绝对角度 = 索引 × 间距"再取模，必须由 active 直接求
   *   2. 回绕（06 → 01）走的是 -40°，不是绕满一圈
   */
  spread: 40,

  /** 展台尺寸（世界单位，16:9）。投影后正面站约 965px，占屏 50% */
  panel: { w: 3.2, h: 1.8 },

  /** facing = cos(夹角) ^ expFacing。压低 → 侧翼更快变暗 */
  expFacing: 1.1,

  /** 亮度 = facing ^ expBright。压低 → 正面与侧翼的亮度差更陡 */
  expBright: 1.9,

  /** 正面站比侧翼站抬起的世界单位 */
  lift: 0.19,
} as const;

export const SPREAD_RAD = (RING.spread * Math.PI) / 180;

/** 站位 i 的弧上角度（弧度），仅用于摆位 */
export const stationTheta = (i: number) => i * SPREAD_RAD;

/**
 * 环旋转到让 active 正对相机时的目标角度。
 *
 * 由 active 直接求而不是靠累加，是为了消掉一类漂移 bug：
 * 累加式（angle -= SPREAD 每次切换）走满一轮会累计 (n-1)×SPREAD，
 * 对开口弧来说这个值不是 360° 的整数倍，于是每循环一圈整环偏移一次，
 * 数学上没错但选中项已经转到缺口里去了。
 */
export const targetAngleFor = (active: number) => -active * SPREAD_RAD;